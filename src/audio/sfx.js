import { AppState } from 'react-native';
import { Audio } from 'expo-av';
import * as FileSystem from 'expo-file-system';
import EFFECT_FILES from './effectFiles';
import SQUISHDOKU_FILES from './squishdokuFiles';
import SORT_FILES from './sortFiles';

// The v3 design's sound: ~40 effects, five music moods and the Crib's tracks, rendered from the
// design's own sfx.js (tools/audio) to files in assets/audio.
//
//   sfx.play('tap')                 one-shot effect
//   const h = sfx.loop('reelLoop')  looping effect → h.setRate(r), h.stop()
//   sfx.music('cozy')               crossfades to that mood (null = silence)
//
// Effects are kept loaded and restarted on each play (a fresh player per
// play is too slow for button taps) — but only a few at a time: every
// expo-av sound is a whole ExoPlayer with its own decoder and threads, and
// keeping all ~30 loaded ran a 2 GB phone out of memory. The least recently
// played effects are released first. Music and effects each have an on/off
// switch (Home → Settings), remembered on the device. The squish screen's
// own squish / coin / release sounds are separate (src/audio/*Sound.js).

// name -> file (generated by tools/audio/encode.py). The button click
// ('tap') is the user's bubble (2026-10-16): single_bubble_1s.wav trimmed to
// start on the bubble (it had 150 ms of silence first) and kept outside
// assets/audio/sfx, which encode.py clears.
// Squishdoku's own effects (sd_*) are tools/audio/squishdoku_sfx.py's, Squish
// Sort's (fs_*) tools/audio/sort_sfx.py's.
const EFFECTS = { ...EFFECT_FILES, ...SQUISHDOKU_FILES, ...SORT_FILES, tap: require('../../assets/audio/bubble_tap.wav') };
// A second click this soon is the same press heard twice (the shared
// Pressable plays it, and some handlers did already).
const TAP_GAP_MS = 100;
let lastTap = 0;

const MUSIC = {
  dream: require('../../assets/audio/music/dream.ogg'),
  party: require('../../assets/audio/music/party.ogg'),
  cozy: require('../../assets/audio/music/cozy.ogg'),
  calm: require('../../assets/audio/music/calm.ogg'),
  mystery: require('../../assets/audio/music/mystery.ogg'),
  // the game's main theme after the splash (the user's own track; Velvet Map
  // Study replaced Butterscotch Bounce on 2026-10-17)
  bounce: require('../../assets/audio/music/velvet_map_study.mp3'),
  // the Crib's rooms and the dance room's club songs (tools/audio/render.mjs --crib)
  crib_living: require('../../assets/audio/music/crib_living.ogg'),
  crib_kitchen: require('../../assets/audio/music/crib_kitchen.ogg'),
  crib_bath: require('../../assets/audio/music/crib_bath.ogg'),
  crib_bed: require('../../assets/audio/music/crib_bed.ogg'),
  crib_dance: require('../../assets/audio/music/crib_dance.ogg'),
  crib_yard: require('../../assets/audio/music/crib_yard.ogg'),
  club_disco: require('../../assets/audio/music/club_disco.ogg'),
  club_house: require('../../assets/audio/music/club_house.ogg'),
  club_synth: require('../../assets/audio/music/club_synth.ogg'),
  club_bounce: require('../../assets/audio/music/club_bounce.ogg'),
  club_turbo: require('../../assets/audio/music/club_turbo.ogg'),
};

// The files are levelled per group (tools/audio/encode.py); this puts the
// music back under the effects. 0.2 is the design's exact balance — a
// little more, so it's heard on a phone speaker.
const MUSIC_VOLUME = 0.3;
// Tracks that didn't go through encode.py's levelling: Velvet Map Study
// is a mastered song, ~6 dB louder (RMS -14.3 dB vs ~-20 dB for the rest),
// so it's played at half volume to sit with the others.
const TRACK_GAIN = { bounce: 0.5 };
const volumeOf = (name) => MUSIC_VOLUME * (TRACK_GAIN[name] ?? 1);
const FADE_IN_MS = 1200;
const FADE_OUT_MS = 900;
// Loaded right away (the rest on first use), so the first tap has a sound.
const WARM = ['tap', 'whoosh'];
// Effects loaded at once, at most (each is one player). A screen that
// plays many different ones fast (Squishdoku) raises it while it's open
// (setBudget), so its sounds aren't reloaded mid-puzzle.
const MAX_LOADED = 8;
let budget = MAX_LOADED;
// Sounds that repeat faster than they ring out get two players, so a new
// one doesn't cut the last one short.
const VOICES = { boxBell: 2 };

const SETTINGS_PATH = `${FileSystem.documentDirectory}soundSettings.json`;

const state = {
  effectsOn: true,
  musicOn: true,
  players: new Map(), // effect name -> Promise<Sound>
  loops: new Set(),
  track: null, // { name, sound }
  want: null,
  fading: new Map(), // Sound -> interval
  active: AppState.currentState === 'active',
  listeners: new Set(),
};

const quiet = (p) => p && p.catch(() => {});

let modeSet = false;
function setMode() {
  if (modeSet) return;
  modeSet = true;
  // Mix with other audio rather than stopping it, and play in silent mode on
  // iOS like the rest of the app's sounds.
  quiet(Audio.setAudioModeAsync({ playsInSilentModeIOS: true, shouldDuckAndroid: true, staysActiveInBackground: false }));
}

// name -> { voices: Promise<Sound|null>[], next, used }
function entry(name) {
  if (!EFFECTS[name]) return null;
  let e = state.players.get(name);
  if (!e) {
    setMode();
    const load = () =>
      Audio.Sound.createAsync(EFFECTS[name], { shouldPlay: false, volume: 1, progressUpdateIntervalMillis: 60000 })
        .then((r) => r.sound)
        .catch(() => null);
    e = { voices: Array.from({ length: VOICES[name] || 1 }, load), next: 0, used: 0 };
    state.players.set(name, e);
    evict(name);
  }
  e.used = Date.now();
  return e;
}

// Release the least recently played effects beyond MAX_LOADED.
function evict(keep) {
  const loaded = Array.from(state.players.entries()).filter(([n]) => n !== keep && !WARM.includes(n));
  const extra = state.players.size - budget;
  if (extra <= 0) return;
  loaded
    .sort((a, b) => a[1].used - b[1].used)
    .slice(0, extra)
    .forEach(([n, e]) => {
      state.players.delete(n);
      e.voices.forEach((v) => v.then((sound) => sound && quiet(sound.unloadAsync())));
    });
}

// ---- effects ---------------------------------------------------------------

// How many effects may stay loaded (null = back to MAX_LOADED).
function setBudget(n) {
  budget = n || MAX_LOADED;
  evict(null);
}

// Load a screen's effects ahead of time: the first play of an effect loads
// its player, which stalls the app for a moment — mid-way through the
// Mystery Box's fast taps that was enough to break the combo.
function preload(names) {
  if (!state.effectsOn) return;
  names.forEach(entry);
}

function play(name, { delay = 0, rate } = {}) {
  if (!state.effectsOn || !state.active) return;
  if (name === 'tap' && !delay) {
    const now = Date.now();
    if (now - lastTap < TAP_GAP_MS) return;
    lastTap = now;
  }
  const go = async () => {
    const e = entry(name);
    if (!e) return;
    const voice = e.voices[e.next];
    e.next = (e.next + 1) % e.voices.length;
    const sound = await voice;
    if (!sound) return;
    // one native call: restart, at this rate if one's given
    quiet(sound.replayAsync(rate ? { rate, shouldCorrectPitch: false } : {}));
  };
  if (delay) setTimeout(go, delay);
  else go();
}

// A looping effect (the reel's ticking, the unlock hold's hum). Each call
// gets its own player so two loops never fight over one.
function loop(name, { volume = 1, rate = 1 } = {}) {
  const handle = { sound: null, stopped: false, volume, rate };
  if (!state.effectsOn || !EFFECTS[name]) return { setRate() {}, setVolume() {}, stop() {} };
  setMode();
  Audio.Sound.createAsync(EFFECTS[name], { shouldPlay: state.active, isLooping: true, volume, rate, shouldCorrectPitch: false, progressUpdateIntervalMillis: 60000 })
    .then(({ sound }) => {
      if (handle.stopped) {
        quiet(sound.unloadAsync());
        return;
      }
      handle.sound = sound;
      state.loops.add(handle);
    })
    .catch(() => {});
  return {
    setRate(r) {
      handle.rate = r;
      if (handle.sound) quiet(handle.sound.setRateAsync(r, false));
    },
    setVolume(v) {
      handle.volume = v;
      if (handle.sound) quiet(handle.sound.setVolumeAsync(v));
    },
    stop() {
      handle.stopped = true;
      state.loops.delete(handle);
      if (handle.sound) quiet(handle.sound.unloadAsync());
    },
  };
}

// ---- music -----------------------------------------------------------------

function fade(sound, from, to, ms, done) {
  const prev = state.fading.get(sound);
  if (prev) clearInterval(prev);
  const steps = Math.max(1, Math.round(ms / 50));
  let i = 0;
  quiet(sound.setVolumeAsync(from));
  const timer = setInterval(() => {
    i++;
    quiet(sound.setVolumeAsync(from + ((to - from) * i) / steps));
    if (i >= steps) {
      clearInterval(timer);
      state.fading.delete(sound);
      done && done();
    }
  }, 50);
  state.fading.set(sound, timer);
}

function stopTrack() {
  const tr = state.track;
  state.track = null;
  if (!tr) return;
  tr.stopped = true;
  if (tr.sound) fade(tr.sound, volumeOf(tr.name), 0, FADE_OUT_MS, () => quiet(tr.sound.unloadAsync()));
}

function startTrack(name) {
  setMode();
  const tr = { name, sound: null, stopped: false };
  state.track = tr;
  Audio.Sound.createAsync(MUSIC[name], { shouldPlay: state.active, isLooping: true, volume: 0, progressUpdateIntervalMillis: 60000 })
    .then(({ sound }) => {
      if (tr.stopped) {
        quiet(sound.unloadAsync());
        return;
      }
      tr.sound = sound;
      fade(sound, 0, volumeOf(name), FADE_IN_MS);
    })
    .catch(() => {});
}

function music(name) {
  state.want = name && MUSIC[name] ? name : null;
  if (state.track && state.track.name === state.want && state.musicOn) return;
  stopTrack();
  if (state.want && state.musicOn) startTrack(state.want);
}

// ---- switches ------------------------------------------------------------

function saveSettings() {
  quiet(FileSystem.writeAsStringAsync(SETTINGS_PATH, JSON.stringify({ effects: state.effectsOn, music: state.musicOn })));
}

function notify() {
  state.listeners.forEach((fn) => fn({ effects: state.effectsOn, music: state.musicOn }));
}

function setEffectsOn(on) {
  state.effectsOn = !!on;
  if (!on) Array.from(state.loops).forEach((h) => h.sound && quiet(h.sound.pauseAsync()));
  saveSettings();
  notify();
}

function setMusicOn(on) {
  state.musicOn = !!on;
  if (!on) stopTrack();
  else if (state.want) music(state.want);
  saveSettings();
  notify();
}

// Settings UI subscribes here; returns the unsubscribe.
function subscribe(fn) {
  state.listeners.add(fn);
  fn({ effects: state.effectsOn, music: state.musicOn });
  return () => state.listeners.delete(fn);
}

// Remembered switches, then a few effects warmed up.
async function init() {
  try {
    const info = await FileSystem.getInfoAsync(SETTINGS_PATH);
    if (info.exists) {
      const saved = JSON.parse(await FileSystem.readAsStringAsync(SETTINGS_PATH));
      state.effectsOn = saved.effects !== false;
      state.musicOn = saved.music !== false;
      notify();
      if (!state.musicOn) stopTrack();
    }
  } catch {
    // defaults
  }
  WARM.forEach(entry);
}

// Nothing plays while the app is in the background.
AppState.addEventListener('change', (next) => {
  const active = next === 'active';
  if (active === state.active) return;
  state.active = active;
  const loops = state.effectsOn ? Array.from(state.loops).map((h) => h.sound) : [];
  const sounds = [state.track && state.track.sound, ...loops].filter(Boolean);
  sounds.forEach((s) => quiet(active ? s.playAsync() : s.pauseAsync()));
});

export default { init, preload, play, loop, music, setEffectsOn, setMusicOn, subscribe, setBudget };
