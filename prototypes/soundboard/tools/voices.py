"""Where each creature's "voice" is: the soundboard plays a short slice of
the creature's own squish recording (assets/audio/creatures/<id>.ogg, the
loop the squish stage plays). For each recording this finds the strongest
squish that starts cleanly: a jump in loudness followed by the most energy
over the slice. Prints the start times (seconds) as JSON for voices.js.

Run: python3 prototypes/soundboard/tools/voices.py > prototypes/soundboard/voices.json
"""
import json
import subprocess
import sys

import numpy as np

SR = 22050
SLICE = 0.42  # seconds of each voice
FRAME = 0.01


def pcm(path):
    raw = subprocess.run(
        ['ffmpeg', '-v', 'error', '-i', path, '-ac', '1', '-ar', str(SR), '-f', 'f32le', '-'],
        check=True, capture_output=True).stdout
    return np.frombuffer(raw, dtype=np.float32)


def best_start(x):
    hop = int(SR * FRAME)
    n = len(x) // hop
    rms = np.sqrt(np.array([np.mean(x[i * hop:(i + 1) * hop] ** 2) for i in range(n)]) + 1e-12)
    win = int(SLICE / FRAME)
    best, at = -1.0, 0
    for i in range(5, n - win):
        before = rms[i - 5:i].mean()
        rise = rms[i] / (before + 1e-6)
        if rise < 1.8:
            continue
        energy = rms[i:i + win].sum()
        score = energy * min(rise, 6)
        if score > best:
            best, at = score, i
    if best < 0:  # no clean onset: the loudest slice
        sums = np.convolve(rms, np.ones(win), 'valid')
        at = int(np.argmax(sums))
    return round(max(0, at - 1) * FRAME, 3), round(float(rms[at:at + win].max()), 4)


out = {}
for cid in range(20):
    start, peak = best_start(pcm(f'assets/audio/creatures/{cid}.ogg'))
    out[cid] = {'start': start, 'peak': peak}
    print(cid, start, peak, file=sys.stderr)
with open(__file__.replace('tools/voices.py', 'voices.js'), 'w') as f:
    f.write('// Generated by tools/voices.py: where each creature\'s voice starts in its\n'
            '// squish recording (assets/audio/creatures/<id>.ogg), and how loud it peaks.\n'
            '// Don\'t edit by hand.\n')
    f.write('window.VOICES = ' + json.dumps(out) + ';\n')
print('wrote voices.js', file=sys.stderr)
