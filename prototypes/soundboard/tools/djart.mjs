// Copies what the soundboard needs from the Crib's catalogue into
// ../djart.js: the DJ Booth's tiers (name, level, price, what it does, the
// songs it plays, its picture and where it stands in the dance room) and
// the dance floor the stage uses. Run it again if the catalogue changes.
// Run: node prototypes/soundboard/tools/djart.mjs
import { writeFileSync } from 'node:fs';
import catalog from '../../../src/crib/catalog.js';
import { CHEAP_RATES } from '../../../src/crib/extra.js';
import { SLOTS, SONGS } from '../../../src/crib/home.js';

const songsN = [CHEAP_RATES.songsN].concat(catalog.rates.songsN);
const tiers = SLOTS.dj.tiers.map((t, i) => {
  const b = (t.back || [])[0];
  return { id: t.id, name: t.name, lvl: t.lvl, coins: t.coins || 0, usd: t.usd || 0, effect: t.effect, songs: songsN[i], back: b ? { x: b.x, y: b.y, w: b.w, h: b.h, svg: b.svg } : null };
});
const floor = SLOTS.floor.tiers.find((t) => t.name === 'Party Floor').floor;
const out = `// Generated by tools/djart.mjs from src/crib (catalog.js, extra.js, home.js). Don't edit by hand.
window.DJ = ${JSON.stringify({ tiers, songs: SONGS, floor }, null, 1)};
`;
writeFileSync(new URL('../djart.js', import.meta.url), out);
console.log(`wrote djart.js: ${tiers.length} DJ tiers, ${SONGS.length} songs`);
