"""Squish Stack's squishy cut-outs (SQUISH_STACK.md): the squishies stand on
each other, so each needs its body alone, without the rig still's margin or
the soft floor shadow under its feet (on a tower that shadow floats in the
air beside the one below).

Reads tools/rig/out/thumbs/<key>.webp (the stills tools/plush-art/publish.mjs
uploads as `thumb.url`), clears the shadow (a flat ~20% alpha: everything at
or under SOLID), crops to the body and writes assets/stack/<key>.webp, plus
src/stack/art.js: key -> { src, ar } (ar = height / width). A creature
published after this ran falls back to its thumb (src/stack/roster.js).

    python tools/stack/fit.py
"""
import pathlib

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
THUMBS = ROOT / 'tools' / 'rig' / 'out' / 'thumbs'
OUT = ROOT / 'assets' / 'stack'
SOLID = 60  # alpha above the shadow's ~51


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob('*.webp'):
        old.unlink()
    rows = []
    total = 0
    for f in sorted(THUMBS.glob('*.webp')):
        im = Image.open(f).convert('RGBA')
        a = im.getchannel('A').point(lambda v: v if v > SOLID else 0)
        im.putalpha(a)
        box = a.getbbox()
        if not box:
            continue
        body = im.crop(box)
        dest = OUT / f'{f.stem}.webp'
        body.save(dest, 'WEBP', quality=86, method=6)
        total += dest.stat().st_size
        rows.append(f"  {f.stem}: {{ src: require('../../assets/stack/{f.stem}.webp'), ar: {body.height / body.width:.3f} }},")
    (ROOT / 'src' / 'stack' / 'art.js').write_text(
        '// Generated by tools/stack/fit.py: each squishy cut out to its body, with no\n'
        '// floor shadow (ar = height / width). Don\'t edit by hand.\n\n'
        'export default {\n' + '\n'.join(rows) + '\n};\n',
        encoding='utf-8',
    )
    print(f'{len(rows)} squishies, {total / 1024:.0f} KB -> assets/stack, src/stack/art.js')


if __name__ == '__main__':
    main()
