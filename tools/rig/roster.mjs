// Checks the server roster (functions/squad.js) against the design's
// (tools/design-v6/squad-store.js) and writes src/squad/moves.js from it.
//   node tools/rig/roster.mjs
// The design numbers its creatures itself; ours are permanent (see the top of
// the roster in functions/squad.js), so creatures are matched by `key`. A
// design creature we don't have yet is listed with the next free id: add it
// to the end of R in squad.js by hand.
import fs from 'node:fs';
import path from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import { design } from './design-roster.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const require = createRequire(import.meta.url);
const { ROSTER } = require(path.join(ROOT, 'functions/squad.js'));

let problems = 0;
const ours = Object.fromEntries(ROSTER.map((c) => [c.key, c]));
let next = ROSTER.length;
for (const d of design) {
  const c = ours[d.key];
  if (!c) {
    console.log(`NEW   ${d.key} (${d.name}, ${d.set}, rarity ${d.rar}) → add as id ${next++}`);
    problems++;
    continue;
  }
  const diff = [['name', d.name], ['set', d.set], ['rar', d.rar], ['pass', d.flag === 'pass']].filter(([k, v]) => c[k] !== v);
  if (diff.length) {
    console.log(`DIFF  ${c.id} ${d.key}: ${diff.map(([k, v]) => `${k} ${JSON.stringify(c[k])} → ${JSON.stringify(v)}`).join(', ')}`);
    problems++;
  }
}
const gone = ROSTER.filter((c) => !design.some((d) => d.key === c.key));
gone.forEach((c) => console.log(`GONE  ${c.id} ${c.key}: not in the design any more (keep its row)`));
console.log(problems ? `${problems} difference(s) to bring into functions/squad.js` : `functions/squad.js matches the design (${ROSTER.length} creatures)`);

// Each squishy's signature move, dance, concept and squish sound, by our id.
const moves = Object.fromEntries(design.filter((d) => ours[d.key]).map((d) => [ours[d.key].id, [d.move, d.dance, d.concept, d.sound]]));
fs.writeFileSync(
  path.join(ROOT, 'src/squad/moves.js'),
  `// Generated by tools/rig/roster.mjs from the design's squad-store.js.\n// Each squishy, by roster id: [move name, dance, concept, squish sound].\nexport default ${JSON.stringify(moves)};\n`,
);
console.log(`→ src/squad/moves.js (${Object.keys(moves).length} moves)`);
