// The squish game's creature (REDESIGN_V6 step 4): the design's "card" — a
// domed plane with the creature's front art, and its back art on the other
// side ("ASMR Creature Squash v5" buildCard). This renders, for every roster
// creature, one texture atlas: the front SVG on the left half, the back SVG on
// the right (2048×1024, transparent PNG: expo-gl decodes textures with stb_image, which reads no WebP), in headless Chrome so the art's
// filters draw exactly as in the design. It also writes the creature's dance
// moves and squish springs (creatures-v2.js MOVES) and head height (for the
// Best Friend crown) to src/squad/cardMoves.js.
//
//   node tools/rig/cards.mjs [key ...]
// Output: tools/rig/out/cards/<key>.png (git-ignored; publish with
// tools/plush-art/publish.mjs --cards) and src/squad/cardMoves.js.
import { spawn } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { tmpdir } from 'node:os';
import http from 'node:http';
import vm from 'node:vm';
import { createRequire } from 'node:module';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const DESIGN = join(ROOT, 'tools', 'design-v6');
const OUT = join(ROOT, 'tools', 'rig', 'out', 'cards');
const OUT_JS = join(ROOT, 'src', 'squad', 'cardMoves.js');
const SIDE = 1024;
const require = createRequire(import.meta.url);
const { ROSTER } = require('../../functions/squad.js');
if (!existsSync(join(DESIGN, 'creatures-v2.js'))) throw new Error('unpack the design zip into tools/design-v6 first');

// --- the moves (creatures-v2.js runs as is, with a stand-in window) ----------------
const win = {};
win.window = win;
vm.runInNewContext(readFileSync(join(DESIGN, 'creatures-v2.js'), 'utf8'), { window: win, document: {}, console });
const MOVE_KEYS = ['idle', 'happy', 'dance'];
const cardMoves = {};
for (const c of ROSTER) {
  const name = c.key[0].toUpperCase() + c.key.slice(1);
  const v2 = win.CREATURES_V2.find((x) => x.name === name);
  const m = (win.SquishMoves.MOVES[name]) || (v2 && v2.moves) || null;
  cardMoves[c.id] = {
    head: v2 ? v2.head : 20,
    moves: m ? Object.fromEntries(MOVE_KEYS.filter((k) => m[k]).map((k) => [k, m[k]])) : null,
    sq: (m && m.sq) || null,
  };
}
writeFileSync(
  OUT_JS,
  `// Generated by tools/rig/cards.mjs from the design's creatures-v2.js — don't edit.\n// Each squishy, by roster id: { head (% from the top, for the crown), moves:\n// { idle, happy, dance } (channel: [base, amp, period ms, phase, shape, extra]),\n// sq: { k, z, x, y, r } (its squish springs) } — moves/sq null when the design has none.\nexport default ${JSON.stringify(cardMoves)};\n`,
);
console.log(`moves → ${OUT_JS}`);

// --- the atlases ---------------------------------------------------------------------
const keys = process.argv.slice(2).length ? process.argv.slice(2) : ROSTER.map((c) => c.key);
mkdirSync(OUT, { recursive: true });
const PORT = 9700 + Math.floor(Math.random() * 200);
const server = http
  .createServer((req, res) => {
    const p = decodeURIComponent(new URL(req.url, 'http://x').pathname);
    if (p === '/') return res.writeHead(200, { 'Content-Type': 'text/html' }).end('<!doctype html><body></body>');
    const file = join(DESIGN, p);
    if (!file.startsWith(DESIGN) || !existsSync(file) || !file.endsWith('.svg')) return res.writeHead(404).end();
    res.writeHead(200, { 'Content-Type': 'image/svg+xml' });
    res.end(readFileSync(file));
  })
  .listen(PORT);

const chromePath = (await import(pathToFileURL(join(ROOT, 'node_modules', 'chrome-launcher', 'dist', 'chrome-finder.js')).href).catch(() => null))
  ?.win32?.()[0] || 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const CDP = 9900 + Math.floor(Math.random() * 90);
const chrome = spawn(chromePath, ['--headless=new', '--no-sandbox', '--hide-scrollbars', `--remote-debugging-port=${CDP}`, `--user-data-dir=${join(tmpdir(), 'rig-cards-' + process.pid)}`, 'about:blank'], { stdio: 'ignore' });
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let page;
for (let i = 0; i < 50 && !page; i++) { await sleep(200); try { page = (await (await fetch(`http://127.0.0.1:${CDP}/json/list`)).json()).find((t) => t.type === 'page'); } catch (e) {} }
if (!page) { chrome.kill(); server.close(); throw new Error('Chrome did not start'); }
const ws = new WebSocket(page.webSocketDebuggerUrl);
await new Promise((r) => ws.addEventListener('open', r));
let id = 0;
const pend = new Map();
ws.addEventListener('message', (e) => { const m = JSON.parse(e.data); if (m.id && pend.has(m.id)) { pend.get(m.id)(m); pend.delete(m.id); } });
const send = (method, params = {}) => new Promise((r) => { const i = ++id; pend.set(i, r); ws.send(JSON.stringify({ id: i, method, params })); });
const evalJs = async (js) => { const r = await send('Runtime.evaluate', { expression: js, returnByValue: true, awaitPromise: true }); return r.result?.result?.value ?? { error: r.result?.exceptionDetails?.exception?.description }; };
await send('Page.navigate', { url: `http://127.0.0.1:${PORT}/` });
await sleep(400);

const ATLAS = (key) => `new Promise((ok) => {
  const load = (side) => new Promise((r) => { const i = new Image(); i.onload = () => r(i); i.onerror = () => r(null); i.src = '/export/tripo/${key}/${key}-' + side + '.svg'; });
  Promise.all([load('front'), load('back')]).then(([f, b]) => {
    if (!f || !b) return ok({ error: 'missing art' });
    const c = document.createElement('canvas'); c.width = ${SIDE * 2}; c.height = ${SIDE};
    const x = c.getContext('2d'); x.drawImage(f, 0, 0, ${SIDE}, ${SIDE}); x.drawImage(b, ${SIDE}, 0, ${SIDE}, ${SIDE});
    ok({ url: c.toDataURL('image/png') });
  });
})`;

let n = 0;
for (const key of keys) {
  const r = await evalJs(ATLAS(key));
  if (!r || !r.url) { console.log('FAILED', key, r && r.error); continue; }
  writeFileSync(join(OUT, `${key}.png`), Buffer.from(r.url.split(',')[1], 'base64'));
  n++;
  process.stdout.write('.');
}
console.log(`\n${n}/${keys.length} card atlases (${SIDE * 2}×${SIDE}) → ${OUT}`);
ws.close();
chrome.kill();
server.close();
