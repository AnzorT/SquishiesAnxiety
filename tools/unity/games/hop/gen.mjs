// Writes unity/Assets/Scripts/Games/Hop/LevelData.g.cs from src/hop/levelData.js (Squish Hop's 100 fixed levels).
//
//   node tools/unity/games/hop/gen.mjs
//
// Run it again whenever levelData.js changes; tools/unity/games/hop/fixtures.mjs + the hop-test project then check
// the C# against the JS.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import LEVEL_DATA from '../../../../src/hop/levelData.js';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const REPO = path.resolve(HERE, '../../../..');
const OUT = path.join(REPO, 'unity/Assets/Scripts/Games/Hop/LevelData.g.cs');

// a C# string literal: printable ASCII as is, everything else as \uXXXX (UTF-16 units, as JS strings are)
function str(s) {
  if (s === null) return 'null';
  if (typeof s !== 'string') throw new Error(`not a string: ${s}`);
  let o = '"';
  for (let i = 0; i < s.length; i++) {
    const c = s.charCodeAt(i);
    if (c === 0x22) o += '\\"';
    else if (c === 0x5c) o += '\\\\';
    else if (c >= 0x20 && c < 0x7f) o += s[i];
    else o += '\\u' + c.toString(16).padStart(4, '0');
  }
  return o + '"';
}
function int(n) {
  if (!Number.isInteger(n) || Math.abs(n) > 2147483647) throw new Error(`not a 32-bit integer: ${n}`);
  return String(n);
}

const KEYS = 'map,room,tier,news,sols,effort,solution';
const lines = LEVEL_DATA.map((d, i) => {
  if (Object.keys(d).join(',') !== KEYS) throw new Error(`level ${i + 1}: fields ${Object.keys(d)}`);
  if (!Array.isArray(d.map)) throw new Error(`level ${i + 1}: map`);
  return `            new LevelDef(new[] { ${d.map.map(str).join(', ')} }, ${str(d.room)}, ${int(d.tier)}, ${str(d.news)}, ${int(d.sols)}, ${int(d.effort)}, ${str(d.solution)}),`;
});

const cs = `// <auto-generated>
// GENERATED by tools/unity/games/hop/gen.mjs from src/hop/levelData.js: Squish Hop's ${LEVEL_DATA.length} fixed levels.
// Don't edit by hand. To regenerate: node tools/unity/games/hop/gen.mjs
// Fields: map (engine letters), room, tier (0 EASY … 3 EXPERT), news (the twist it brings in), sols (full clears),
// effort (solver moves tried before the clear), solution (the clear as U R D L).
// </auto-generated>
namespace SquishSquad.Games.Hop
{
    public static class LevelData
    {
        public static readonly LevelDef[] All =
        {
${lines.join('\n')}
        };
    }
}
`;
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, cs);
console.log(`wrote ${path.relative(REPO, OUT)} (${LEVEL_DATA.length} levels)`);
