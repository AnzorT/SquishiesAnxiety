// Writes unity/Assets/Scripts/Games/Squishdoku/LevelData.g.cs from src/squishdoku/levelData.js (Squishdoku's 600
// fixed levels), so the Unity port reads the very same boards. Run: node tools/unity/games/squishdoku/gen.mjs
import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import LEVEL_DATA from '../../../../src/squishdoku/levelData.js';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../../../..');
const out = resolve(root, 'unity/Assets/Scripts/Games/Squishdoku/LevelData.g.cs');

const str = (s) => {
  if (typeof s !== 'string' || !/^[a-z0-9]*$/.test(s)) throw new Error(`unexpected level string ${JSON.stringify(s)}`);
  return `"${s}"`;
};
const rows = LEVEL_DATA.map((d, i) => {
  if (!Number.isInteger(d.n) || !Number.isInteger(d.e)) throw new Error(`level ${i + 1}: n / e not integers`);
  return `            new LevelDatum(${d.n}, ${str(d.r)}, ${str(d.s)}, ${str(d.c)}, ${d.e}), // ${i + 1}`;
});

const cs = `// <auto-generated>
// GENERATED by tools/unity/games/squishdoku/gen.mjs from src/squishdoku/levelData.js. Don't edit by hand.
// Regenerate: node tools/unity/games/squishdoku/gen.mjs
// </auto-generated>
// Squishdoku's ${LEVEL_DATA.length} levels, one fixed board each (SQUISHDOKU.md "600 levels"):
//   N  the grid size
//   R  each cell's patch, row by row (a = patch 0, b = patch 1, ...)
//   S  each row's creature: its column
//   C  each patch's colour (an index into theme.js PATCHES)
//   E  the effort: how much thinking it takes (Engine.Grade)
namespace SquishSquad.Games.Squishdoku
{
    public sealed class LevelDatum
    {
        public readonly int N;
        public readonly string R;
        public readonly string S;
        public readonly string C;
        public readonly int E;

        public LevelDatum(int n, string r, string s, string c, int e)
        {
            N = n;
            R = r;
            S = s;
            C = c;
            E = e;
        }
    }

    public static class LevelData
    {
        public static readonly LevelDatum[] All =
        {
${rows.join('\n')}
        };
    }
}
`;
writeFileSync(out, cs);
console.log(`wrote ${out} (${LEVEL_DATA.length} levels)`);
