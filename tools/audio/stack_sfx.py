"""Squish Stack's sound effects (SQUISH_STACK.md), synthesized with
squishdoku_sfx.py's building blocks: a squishy lifted off its stack, landing
on another squishy or on a cushion, a big one squashing a small one flat and
bouncing home, the undo, the hint, a tap on an empty cushion, and the chime
for a new twist. (Stars, coins, confetti, the win, the countdown tick and
time's up are Squishdoku's own sd_* sounds.)

Writes assets/audio/stack/st_*.wav (all short) and src/audio/stackFiles.js,
the list src/audio/sfx.js merges into its effects.

    python tools/audio/stack_sfx.py
"""
import pathlib
import sys

import numpy as np
import soundfile as sf

HERE = pathlib.Path(__file__).parent
sys.path.insert(0, str(HERE))
import squishdoku_sfx as sd  # noqa: E402  (its building blocks; importing it renders its sounds, not writes them)
from squishdoku_sfx import (  # noqa: E402
    SR, band, bell, bloop, boing, click, decay, droplet, env, finish, low, mix, noise, note, osc, reverb, shimmer,
    squish, sweep, sweep_filter, thump, whoosh,
)

ROOT = HERE.parent.parent
OUT = ROOT / 'assets' / 'audio' / 'stack'

S = {}

# lifted off the stack: a rising droplet and a little suction pop
_unstick = sweep_filter(noise(0.06), 600, 3200, 'low') * decay(int(0.06 * SR), 0.02, a=0.003)
S['st_lift'] = (mix([(droplet(380, 1150, 0.08), 0, 1.0), (_unstick, 0, 0.35), (click(0.006, 4200), 0.01, 0.15)]), 0.42)

# landing on another squishy: a wet squish, a soft bloop and a body thump
# (the game plays it faster for small ones and slower for big ones)
S['st_land'] = (reverb(mix([(squish(0.16, 2400, 380), 0, 0.9), (bloop(320, 110, 0.14, 0.06), 0, 0.8), (thump(90, 0.16, 2.2), 0, 0.55)]), 0.4, 0.12), 0.62)

# landing on a cushion: a deep pillowy whump with a puff of air
_puff = low(noise(0.2), 700) * env(int(0.2 * SR), a=0.004, d=0.16, s=0.0, r=0.03)
S['st_cushion'] = (reverb(mix([(thump(58, 0.32, 2.6), 0, 1.0), (_puff, 0, 0.8), (squish(0.1, 1400, 300), 0.01, 0.35)]), 0.5, 0.14), 0.66)

# a big one dropped on a small one: a heavy SQUASH, the small one squeaks
_squeak = osc(np.concatenate([sweep(900, 1500, 0.06), sweep(1500, 700, 0.14)]), kind='tri') * env(int(0.2 * SR), a=0.004, d=0.15, s=0.4, r=0.04)
S['st_ouch'] = (reverb(mix([(squish(0.24, 2800, 220), 0, 1.0), (thump(70, 0.28, 3.0), 0, 0.8), (_squeak, 0.06, 0.55), (sd.grumble(0.18), 0.16, 0.35)]), 0.5, 0.14), 0.8)

# ...and the big one boings back home
S['st_bounce'] = (mix([(boing(240, 0.32), 0, 0.9), (whoosh(0.24, 500, 2600, False), 0.02, 0.35)]), 0.58)

# undo: a quick reverse swoosh and a soft pop
S['st_undo'] = (mix([(whoosh(0.2, 2600, 500, False), 0, 0.6), (bloop(520, 260, 0.08, 0.03), 0.12, 0.7)]), 0.45)

# the hint: two magic dings and a sparkle
_dings = mix([(bell(note('A6'), 0.5, tau=0.16), 0, 0.7), (bell(note('E7'), 0.6, tau=0.2), 0.11, 0.65)])
S['st_hint'] = (reverb(mix([(_dings, 0, 1.0), (shimmer(0.45, 5000, 10000, 40), 0.06, 0.35)]), 0.7, 0.2), 0.6)

# a tap on an empty cushion: a soft pat
S['st_empty'] = (mix([(thump(120, 0.12, 1.6), 0, 0.8), (band(noise(0.05), 300, 1200) * decay(int(0.05 * SR), 0.015), 0, 0.5)]), 0.4)

# something new on this level (the goal card, the clock, a 4th cushion)
_news = mix([(bell(note(n), 0.5, tau=0.18, index=1.4), 0.08 * i, 0.55) for i, n in enumerate(['G5', 'C6', 'E6', 'G6'])])
S['st_news'] = (reverb(mix([(_news, 0, 1.0), (shimmer(0.5, 4500, 9500, 40), 0.15, 0.3), (whoosh(0.3, 800, 5000, False), 0, 0.2)]), 0.8, 0.22), 0.62)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob('*.wav'):
        old.unlink()
    total = 0
    for name, (data, peak) in S.items():
        x = finish(np.asarray(data, dtype=np.float64), peak, max_s=1.2)
        assert np.isfinite(x).all(), name
        dest = OUT / f'{name}.wav'
        sf.write(dest, x.astype(np.float32), SR, subtype='PCM_16')
        size = dest.stat().st_size
        total += size
        print(f'{dest.relative_to(ROOT)}  {len(x) / SR:5.2f}s  {size / 1024:6.1f} KB')
    lines = [f"  {n}: require('../../assets/audio/stack/{n}.wav')," for n in sorted(S)]
    header = ["// Generated by tools/audio/stack_sfx.py — Squish Stack's sound effects.", "// Don't edit by hand.", '', 'export default {']
    (ROOT / 'src' / 'audio' / 'stackFiles.js').write_text('\n'.join(header + lines + ['};', '']), encoding='utf8')
    print(f'{len(S)} sounds, {total / 1024:.0f} KB')


if __name__ == '__main__':
    main()
