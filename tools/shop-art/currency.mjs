// Renders the v6 design's currency art (squish-currency.js: gold coins
// stamped with a creature, gems cut in a creature's shape) to PNGs, run for
// real in headless Chrome. The design builds them on a canvas at page load;
// the app shows the same pictures as images.
//
//   node tools/shop-art/currency.mjs   (after unpacking the zip into tools/design-v6)
// Output: assets/squad/currency/coin-<key>.png and gem-<key>.png (160×160,
// the design's own size), and src/squad/currencyArt.js (the require map, in
// the design's order: COIN[0] / GEM[0] are the ones the lobby shows).

import fs from 'node:fs';
import http from 'node:http';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { connect, evaluate } from './cdp.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../..');
const DESIGN = path.join(ROOT, 'tools/design-v6');
const OUT = path.join(ROOT, 'assets/squad/currency');
const OUT_JS = path.join(ROOT, 'src/squad/currencyArt.js');
const PORT = 9600 + Math.floor(Math.random() * 300);

const MIME = { '.html': 'text/html', '.js': 'text/javascript', '.svg': 'image/svg+xml' };
const server = http
  .createServer((req, res) => {
    const url = new URL(req.url, 'http://x');
    if (url.pathname === '/currency') {
      res.writeHead(200, { 'Content-Type': 'text/html' });
      res.end('<!doctype html><html><body><script src="/squish-currency.js"></script></body></html>');
      return;
    }
    const file = path.join(DESIGN, decodeURIComponent(url.pathname));
    if (!file.startsWith(DESIGN) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) {
      res.writeHead(404);
      res.end();
      return;
    }
    res.writeHead(200, { 'Content-Type': MIME[path.extname(file)] || 'application/octet-stream' });
    fs.createReadStream(file).pipe(res);
  })
  .listen(PORT);

const READ = `new Promise((done) => {
  const take = () => {
    const S = window.SquishCoin;
    done({ coins: S.COINS.map((k, i) => [k, S.coin(i)]), gems: S.GEMS.map((k, i) => [k, S.gem(i)]) });
  };
  if (window.SquishCoin && window.SquishCoin.ready) take();
  else window.addEventListener('squishcoin', take);
})`;

const { send, close } = await connect();
let art;
try {
  await send('Page.navigate', { url: `http://127.0.0.1:${PORT}/currency` });
  for (let i = 0; i < 60 && !art; i++) {
    await new Promise((r) => setTimeout(r, 200));
    art = await evaluate(send, `window.SquishCoin ? ${READ} : null`).catch(() => null);
  }
  if (!art) throw new Error('squish-currency.js never finished');
} finally {
  close();
  server.close();
}

fs.mkdirSync(OUT, { recursive: true });
const write = (kind, list) =>
  list.map(([key, url]) => {
    if (!url || !url.startsWith('data:image/png;base64,')) throw new Error(`${kind} ${key}: no picture`);
    fs.writeFileSync(path.join(OUT, `${kind}-${key}.png`), Buffer.from(url.split(',')[1], 'base64'));
    return `require('../../assets/squad/currency/${kind}-${key}.png')`;
  });
const coins = write('coin', art.coins);
const gems = write('gem', art.gems);
fs.writeFileSync(
  OUT_JS,
  `// Generated by tools/shop-art/currency.mjs — don't edit.\n// The design's currency art (squish-currency.js), 160×160: coins stamped\n// with ${art.coins.map((c) => c[0]).join(', ')}; gems shaped like ${art.gems.map((g) => g[0]).join(', ')}.\nexport const COIN = [${coins.join(', ')}];\nexport const GEM = [${gems.join(', ')}];\n`,
);
console.log(`${coins.length} coins, ${gems.length} gems → ${path.relative(ROOT, OUT)}, ${path.relative(ROOT, OUT_JS)}`);
