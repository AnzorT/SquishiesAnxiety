"""The creatures' four border looks (REDESIGN_V9, 2026-11-16: the user's Squish-Squad-assets.zip, characters/<set>/
<Name>_look-<n>-<style>.png, 512 x 512) as the pictures the app shows wherever a creature is drawn still, picked in
Firestore config/roster (`look`, `looks`; src/squad/looks.js):
    look 1  shading only           look 3  bold ink line
    look 2  thin ink line          look 4  bold colour line (the game's default)
Written once to android/app/src/main/assets/looks/<n>/<creature key>.webp (384 px, about 13 KB each), where the app's
screens (asset:/looks/...) and the menu's pages (../looks/...) both read them; and src/squad/lookKeys.js, the creatures
that have them (matched to functions/squad.js by name).

    python -m pip install --user pillow   # once
    python tools/looks/encode.py "C:/Users/<you>/Desktop/Squish-Squad-assets.zip"
"""
import io
import json
import pathlib
import re
import subprocess
import sys
import zipfile

from PIL import Image

ROOT = pathlib.Path(__file__).resolve().parent.parent.parent
OUT = ROOT / 'android' / 'app' / 'src' / 'main' / 'assets' / 'looks'
SIZE = 384
norm = lambda s: re.sub(r'[^a-z]', '', s.lower())

# the roster's names and keys, from the server's own list
roster = json.loads(subprocess.check_output(['node', '-e', "const s=require('./functions/squad.js');console.log(JSON.stringify(s.ROSTER.map(c=>[c.key,c.name])))"], cwd=ROOT))
by_name = {norm(name): key for key, name in roster}

z = zipfile.ZipFile(sys.argv[1])
done, total = set(), 0
for info in z.infolist():
    m = re.search(r'characters/[^/]+/(.+)_look-(\d)-[^/]+\.png$', info.filename)
    if not m:
        continue
    key = by_name.get(norm(m.group(1)))
    if not key:
        print('not in the roster:', m.group(1))
        continue
    im = Image.open(io.BytesIO(z.read(info))).convert('RGBA').resize((SIZE, SIZE), Image.LANCZOS)
    dest = OUT / m.group(2) / f'{key}.webp'
    dest.parent.mkdir(parents=True, exist_ok=True)
    im.save(dest, 'WEBP', quality=82, method=6)
    total += dest.stat().st_size
    done.add(key)

keys = sorted(done)
(ROOT / 'src' / 'squad' / 'lookKeys.js').write_text(
    '// Generated by tools/looks/encode.py: the creatures with the four border looks (android/app/src/main/assets/looks).\n'
    'export default ' + json.dumps(keys) + ';\n', encoding='utf8')
missing = [name for key, name in roster if key not in done]
print(f'{len(keys)} creatures x 4 looks, {total / 1024 / 1024:.1f} MB; without looks: {", ".join(missing) or "none"}')
